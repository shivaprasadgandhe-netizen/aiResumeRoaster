"use client";

import React, { useState } from "react";
import Link from "next/link";
import { toast } from "sonner";
import { Share2, Download, Printer, ArrowLeft, Check } from "lucide-react";
import { RoastResult } from "@/types/roast";

interface ReportActionsProps {
  roastId: string;
  fileName: string;
  data: RoastResult;
}

export function ReportActions({ roastId, fileName, data }: ReportActionsProps) {
  const [copied, setCopied] = useState(false);

  const handleCopyLink = async () => {
    try {
      const shareUrl = `${window.location.origin}/share/${roastId}`;
      await navigator.clipboard.writeText(shareUrl);
      setCopied(true);
      toast.success("Share link copied to clipboard!");
      setTimeout(() => setCopied(false), 2500);
    } catch {
      toast.error("Failed to copy link.");
    }
  };

  const handleDownloadMarkdown = () => {
    const mdContent = `# AI Resume Roast Report
**File Name**: ${fileName}
**Overall Score**: ${data.overallScore}/100
**Verdict**: "${data.verdict}"

---

## Section Breakdown
- Formatting: ${data.sections.formatting}/100
- Content: ${data.sections.content}/100
- Impact: ${data.sections.impact}/100
- Clarity: ${data.sections.clarity}/100

${data.jobMatch ? `\n## Target Job Match: ${data.jobMatch.score}%\n${data.jobMatch.summary}\n` : ""}

---

## The Roast
${data.roast.map((p) => `> ${p}`).join("\n\n")}

---

## Redeeming Strengths
${data.strengths.map((s) => `- ${s}`).join("\n")}

---

## Actionable Fixes
${data.improvements.map((imp) => `- ${imp}`).join("\n")}

---

## Missing ATS Keywords
${data.atsKeywordsMissing.map((kw) => `\`${kw}\``).join(", ")}

---
*Generated by AI Resume Roaster • Powered by Next.js 14 & Google Gemini*
`;

    const blob = new Blob([mdContent], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `resume-roast-${fileName.replace(/\.[^/.]+$/, "")}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
    toast.success("Markdown report downloaded!");
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="flex flex-wrap items-center justify-between gap-3 pt-6 border-t border-neutral-200 dark:border-neutral-800 print:hidden">
      <Link
        href="/"
        className="inline-flex items-center gap-1.5 px-4 py-2 rounded-xl border border-neutral-300 dark:border-neutral-700 hover:bg-neutral-100 dark:hover:bg-neutral-800 text-xs sm:text-sm font-semibold transition-colors"
      >
        <ArrowLeft className="w-4 h-4" />
        Roast Another Resume
      </Link>

      <div className="flex flex-wrap items-center gap-2">
        <button
          onClick={handleCopyLink}
          className="inline-flex items-center gap-1.5 px-4 py-2 rounded-xl bg-flame-500 hover:bg-flame-600 text-white text-xs sm:text-sm font-bold shadow-md shadow-flame-500/20 transition-all active:scale-95"
        >
          {copied ? <Check className="w-4 h-4" /> : <Share2 className="w-4 h-4" />}
          {copied ? "Link Copied!" : "Share Roast"}
        </button>

        <button
          onClick={handleDownloadMarkdown}
          className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl border border-neutral-300 dark:border-neutral-700 bg-white dark:bg-charcoal-850 hover:bg-neutral-100 dark:hover:bg-neutral-800 text-neutral-800 dark:text-neutral-200 text-xs sm:text-sm font-semibold transition-colors"
          title="Download Markdown Report"
        >
          <Download className="w-4 h-4" />
          <span className="hidden sm:inline">Export</span> .MD
        </button>

        <button
          onClick={handlePrint}
          className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl border border-neutral-300 dark:border-neutral-700 bg-white dark:bg-charcoal-850 hover:bg-neutral-100 dark:hover:bg-neutral-800 text-neutral-800 dark:text-neutral-200 text-xs sm:text-sm font-semibold transition-colors"
          title="Print or Save PDF"
        >
          <Printer className="w-4 h-4" />
          <span className="hidden sm:inline">Print</span>
        </button>
      </div>
    </div>
  );
}
